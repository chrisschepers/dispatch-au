const fs = require('fs');
const path = require('path');
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require('expo/config-plugins');

// iOS 27 stops an app at launch (brk 0 in UIKit's scene connection, before
// any app code runs) unless it adopts the scene-based life cycle. TestFlight
// 1.0.3 (11) crashed this way on the iPhone Duo with iOS 27.2. Expo 57's
// template still makes the window in the app delegate and has no scene
// manifest; Expo 58 ships ExpoAppSceneDelegate for exactly this reason
// ("Required by the iOS 27, which asserts at launch unless the app adopts the
// scene-based life cycle"). Until this app moves to Expo 58, this plugin does
// the same as the Expo 58 template: a scene manifest, a SceneDelegate that
// makes the window and starts React Native in it, and an app delegate that
// only creates the React Native factory. Remove it when upgrading to Expo 58
// (its own SceneDelegate takes over).

// Plain ObjC name (@objc(SceneDelegate) below): the Swift module is
// DispatchVictoria (with-native-module-name), not the product name, so a
// module-qualified class name would be easy to get wrong.
const SCENE_DELEGATE_CLASS = 'SceneDelegate';
const MODULE_NAME = 'main';

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default Configuration',
        UISceneDelegateClassName: SCENE_DELEGATE_CLASS,
      },
    ],
  },
};

const SCENE_DELEGATE_SWIFT = `// Generated by plugins/with-scene-delegate.cjs. Do not edit.
//
// The scene-based life cycle that iOS 27 requires at launch, modelled on
// Expo 58's ExpoAppSceneDelegate: make the window from the connecting scene,
// start React Native in it, and hand scene events back to the app delegate,
// which UIKit no longer calls for them under scenes.
import UIKit
import React
internal import Expo

@objc(${SCENE_DELEGATE_CLASS})
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }
    guard let appDelegate = self.appDelegate, let factory = appDelegate.reactNativeFactory else {
      fatalError("SceneDelegate: the app delegate did not create its React Native factory.")
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window keeps working
    // (expo-system-ui, older React Native helpers).
    appDelegate.window = window

    factory.startReactNative(
      withModuleName: "${MODULE_NAME}",
      in: window,
      launchOptions: Self.launchOptions(connectionOptions))
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  // Links while running. The app delegate's override passes them to the
  // Expo subscribers and to RCTLinkingManager (JS 'url' event).
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    let application = UIApplication.shared
    for context in URLContexts {
      var options: [UIApplication.OpenURLOptionsKey: Any] = [:]
      if let source = context.options.sourceApplication {
        options[.sourceApplication] = source
      }
      if let annotation = context.options.annotation {
        options[.annotation] = annotation
      }
      options[.openInPlace] = context.options.openInPlace
      _ = appDelegate?.application(application, open: context.url, options: options)
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }

  // Under scenes a link or universal link that cold-starts the app comes in
  // the connection options instead of the launch options. Linking.getInitialURL
  // reads the launch options, so rebuild them (same keys as Expo 58).
  private static func launchOptions(
    _ connectionOptions: UIScene.ConnectionOptions
  ) -> [UIApplication.LaunchOptionsKey: Any]? {
    var options: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      options[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    if let activity = connectionOptions.userActivities.first(where: {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }) {
      options[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey")] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }
    return options.isEmpty ? nil : options
  }
}
`;

// The block in Expo 57's AppDelegate that makes a screen-sized window and
// starts React Native in didFinishLaunching. Under scenes the SceneDelegate
// does this; the factory itself stays in the app delegate.
const WINDOW_BLOCK =
  /\n#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "([^"]+)",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/;

function removeWindowFromAppDelegate(contents) {
  if (contents.includes('scene-based life cycle: SceneDelegate')) return contents;
  const match = contents.match(WINDOW_BLOCK);
  if (!match) {
    throw new Error(
      'with-scene-delegate: the window block in AppDelegate.swift was not found. ' +
        'The Expo template changed; check the scene set-up (Expo 58 has its own SceneDelegate).',
    );
  }
  if (match[1] !== MODULE_NAME) {
    throw new Error(`with-scene-delegate: AppDelegate starts module "${match[1]}", SceneDelegate starts "${MODULE_NAME}".`);
  }
  return contents.replace(
    WINDOW_BLOCK,
    '\n    // scene-based life cycle: SceneDelegate makes the window and starts React\n' +
      '    // Native in it (plugins/with-scene-delegate.cjs, required by iOS 27).\n',
  );
}

function withSceneDelegate(config) {
  config = withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = SCENE_MANIFEST;
    return mod;
  });

  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== 'swift') {
      throw new Error('with-scene-delegate expects a Swift AppDelegate.');
    }
    mod.modResults.contents = removeWindowFromAppDelegate(mod.modResults.contents);
    return mod;
  });

  config = withDangerousMod(config, [
    'ios',
    async (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const file = path.join(mod.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift');
      await fs.promises.writeFile(file, SCENE_DELEGATE_SWIFT);
      return mod;
    },
  ]);

  return withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: `${projectName}/SceneDelegate.swift`,
      groupName: projectName,
      project: mod.modResults,
    });
    return mod;
  });
}

module.exports = withSceneDelegate;
module.exports.SCENE_MANIFEST = SCENE_MANIFEST;
module.exports.SCENE_DELEGATE_SWIFT = SCENE_DELEGATE_SWIFT;
module.exports.removeWindowFromAppDelegate = removeWindowFromAppDelegate;
